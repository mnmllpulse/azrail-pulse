  expect((controls.querySelector('#web-flow-back') as HTMLButtonElement).disabled).toBe(true);
  expect((result.querySelector('.web-workbench') as HTMLElement).hidden).toBe(true);
  (controls.querySelector('#web-flow-next') as HTMLButtonElement).click();
  expect(notice).toHaveBeenCalled();
  expect(controls.querySelector('#web-step-brief')).toBeTruthy();
  const fields=controls.querySelectorAll<HTMLInputElement|HTMLTextAreaElement>('.web-flow-field input, .web-flow-field textarea');
  fields[0].value='Ателье Север';fields[0].dispatchEvent(new w.Event('input'));
  fields[1].value='Шьём пальто для города и оставляем форму заявки.';fields[1].dispatchEvent(new w.Event('input'));
  (controls.querySelector('#web-flow-next') as HTMLButtonElement).click();
