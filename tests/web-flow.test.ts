  const result=w.document.createElement('div');
  w.document.body.append(controls,result);
  const notice=vi.fn();
  const context={meta:studioModule,controls,result,account:null,projectId:'',composer:w.document.createElement('form'),missionPanel:w.document.createElement('div'),api:vi.fn(async()=>({items:[]})),blobAPI:vi.fn(),notice,failure:vi.fn(),mountDraft:vi.fn(),setMediaCleanup:vi.fn(),setLastBlob:vi.fn(),current:()=>true} as unknown as StudioModuleContext;
