  const w=new Window({url:'https://azrail-pulse.mnmllpulse.workers.dev/studios/web',settings:{disableCSSFileLoading:true,disableJavaScriptFileLoading:true}});
  windows.push(w);
  vi.stubGlobal('window',w);
