import {afterEach,describe,expect,it,vi} from 'vitest';
import {Window} from 'happy-dom';
import type {StudioModuleContext} from '../ui/studio-types';
import {blankSite,designFiles,nextFiles,nextTemplate,proposeSite,reasonSite,siteFiles,siteText,zipStore} from '../ui/web-site';
import {readWeakness,referenceFromHtml,summarizeReference} from '../src/lib/web-sites';

const windows:Window[]=[];
afterEach(()=>{for(const w of windows)w.close();windows.length=0;vi.unstubAllGlobals();});

describe('site from a brief',()=>{
 it('builds pages from the brief and leaves reviews as drafts',()=>{
  const flow=blankSite();
  flow.name='Ателье Север';
  flow.business='Шьём пальто для города.';
  flow.audience='людей, которым нужен один хороший крой';
  flow.goal='leads';
  flow.pages=flow.pages.map(page=>page.id==='cases'?{...page,on:false}:page);
  const files=siteFiles(flow);
  const index=files.find(file=>file.path==='index.html')?.text??'';
  expect(files.map(file=>file.path)).toContain('styles.css');
  expect(files.map(file=>file.path)).not.toContain('cases.html');
  expect(index).toContain('Ателье Север');
  expect(index).not.toContain('azrail-site-edit');
  expect(index).toContain('Шьём пальто');
  expect(index).toContain('name="description"');
  expect(index.match(/<h1/g)).toHaveLength(1);
  expect(files.find(file=>file.path==='styles.css')?.text).toContain('prefers-reduced-motion');
  expect(index).toContain('не выдумывает');
  expect(index.toLowerCase()).not.toContain('lorem');
  expect(files.find(file=>file.path==='styles.css')?.text).toContain('#140d10');
  const zip=zipStore(files);
  expect(zip[0]).toBe(0x50);
  expect(zip[1]).toBe(0x4b);
  expect(new TextDecoder().decode(zip)).toContain('index.html');
 });
 it('keeps an edited line',()=>{
  const flow=blankSite();
  flow.name='Ателье';
  flow.business='Пальто.';
  flow.edits['home:hero.title']='Северный крой';
  expect(siteText(flow,'home:hero.title')).toBe('Северный крой');
 });
 it('builds a different structure for a tailor and a law office, and a Next project',()=>{
  const tailor=proposeSite({...blankSite(),name:'Ателье Север',business:'Шьём пальто для города.'});
  const law=proposeSite({...blankSite(),name:'Бюро',business:'Юридическая практика для компаний.'});
  expect(tailor.template).toBe('creative');
  expect(law.template).toBe('corporate');
  expect(tailor.pages.map(page=>page.title).join()).not.toBe(law.pages.map(page=>page.title).join());
  expect(tailor.pages.some(page=>page.title==='Главная')).toBe(true);
  const next=nextFiles(tailor);
  expect(next.some(file=>file.path==='package.json')).toBe(true);
  expect(next.some(file=>file.path==='app/page.tsx')).toBe(true);
  expect(next.find(file=>file.path==='app/layout.tsx')?.text).toContain('{children}');
  const sample=referenceFromHtml('<html class="theme-dark"><title>Чужой дом</title><nav><a>Главная</a><a>Работы</a><a>Контакты</a></nav><h1>Их слоган</h1></html>');
  expect(sample.tone).toBe('dark');
  expect(sample.nav).toContain('Работы');
  expect(sample.title).toBe('Чужой дом');
  const crowded=readWeakness({nav:['1','2','3','4','5','6'],headings:['Их секретный слоган'],tone:'light'});
  expect(crowded).toContain('меню длинное');
  expect(crowded).not.toContain('слоган');
  const summary=summarizeReference('<html><title>Чужой дом</title><nav><a>Главная</a><a>Работы</a><a>Контакты</a></nav><h1>Их слоган</h1></html>');
  expect(JSON.stringify(summary)).not.toContain('слоган');
  const plain={...blankSite(),name:'Свет',business:'Делаем свет для домов и пространств.'};
  const leads=proposeSite({...plain,goal:'leads'});
  const portfolio=proposeSite({...plain,goal:'portfolio'});
  const launch=proposeSite({...plain,goal:'launch'});
  expect(leads.pages.map(page=>page.title).join()).not.toBe(portfolio.pages.map(page=>page.title).join());
  expect(launch.pages.map(page=>page.title)).toEqual(['Главная','Предложение','Старт']);
  const reason=reasonSite(leads,[]);
  expect(reason.weak).toContain('брифа');
  expect(reason.accent.length).toBeGreaterThan(10);
  const design=designFiles(leads);
  expect(design.some(file=>file.path==='tokens.json'&&file.text.includes(leads.palette))).toBe(true);
  expect(design.some(file=>file.path==='home.svg')).toBe(true);
  expect(design.find(file=>file.path==='README.md')?.text).toContain('Figma');
 });
});

