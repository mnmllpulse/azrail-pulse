import { describe, expect, it } from "vitest";
import { computerTask } from "../ui/chat-agent";

describe("просьбы про компьютер уходят в миссию", () => {
  it.each([
    "Создай на рабочем столе папку test-agent и запиши в неё файл hello.txt с текстом привет",
    "создай папку на рабочем столе",
    "Запиши файл в документах",
    "Найди на моём компьютере файл с паролями от сайта",
    "открой браузер",
    "Открой мой браузер и зайди на ютуб",
    "опубликуй видео на ютуб",
    "Удали файлы в загрузках",
    "запусти в терминале npm install",
    "Установи на компьютере node",
  ])("ловит: %s", (text) => expect(computerTask(text)).toBe(true));

  it.each([
    "привет",
    "Создай страницу сайта про кофе",
    "Расскажи про рабочий стол Windows",
    "что такое браузер",
    "Напиши функцию сортировки",
    "Создай папку src и файл index.ts",
    "x".repeat(5000),
    "",
  ])("не трогает: %s", (text) => expect(computerTask(text)).toBe(false));
});
