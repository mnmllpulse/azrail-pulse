import {afterEach,describe,expect,it,vi} from 'vitest';
import {Window} from 'happy-dom';
import type {StudioModuleContext} from '../ui/studio-types';
import {developedRequest,interpretMusicCommand,partChangeText,setDirectionFlags,sketchRequest,sketchRequests,type DirectionPrefs} from '../ui/music-direction';

const windows:Window[]=[];
afterEach(()=>{for(const w of windows)w.close();windows.length=0;vi.unstubAllGlobals();});

function realm(){
 const w=new Window({url:'https://azrail-pulse.mnmllpulse.workers.dev/studios/music',settings:{disableCSSFileLoading:true,disableJavaScriptFileLoading:true}});
 windows.push(w);
 vi.stubGlobal('window',w);
 vi.stubGlobal('document',w.document);
 vi.stubGlobal('HTMLElement',w.HTMLElement);
 vi.stubGlobal('Event',w.Event);
 return w;
}
const prefs:DirectionPrefs={bpm:null,keyRoot:'',scale:'minor',direction:'house',mood:'hypnotic',likes:{rhythm:true,bass:true,atmosphere:true,energy:false},fragment:null,fileName:'ref.mp3'};

describe('Music direction start',()=>{
 it('opens on a drop zone and keeps manual controls folded',async()=>{
  const w=realm();
  const {studioModule}=await import('../ui/studio-modules/music');
  const controls=w.document.createElement('div');
  const result=w.document.createElement('div');
  w.document.body.append(controls,result);
  const notice=vi.fn();
  const context={meta:studioModule,controls,result,account:null,projectId:'',composer:w.document.createElement('form'),missionPanel:w.document.createElement('div'),api:vi.fn(async()=>({items:[]})),blobAPI:vi.fn(),notice,failure:vi.fn(),mountDraft:vi.fn(),setMediaCleanup:vi.fn(),setLastBlob:vi.fn(),current:()=>true} as unknown as StudioModuleContext;
  await studioModule.mount(context);
  expect(controls.querySelector('#music-listen-build')?.textContent).toBe('Собрать');
  expect(controls.querySelector('#music-listen-play')?.textContent).toBe('Слушать');
  expect(controls.querySelector<HTMLDetailsElement>('#music-bench')?.open).toBe(false);
  expect(controls.querySelector('#music-drop')?.textContent).toContain('Перетащи MP3');
  expect(controls.querySelector('#music-shelf')?.textContent).toContain('ориентир из файла');
  expect(controls.querySelector('#music-shelf')?.textContent).toContain('Мелодичнее');
  expect(controls.querySelector('#music-shelf')?.textContent).toContain('Профессиональнее');
  expect(controls.textContent).toContain('Загрузить сухую фразу');
  expect(controls.querySelector('#music-direction-stop')?.textContent).toBe('Остановить сборку');
  expect(controls.querySelector('#music-direction-scratch')?.textContent).toBe('Создать с нуля');
  expect(controls.querySelector('#music-direction-resume')?.textContent).toBe('Продолжить мой проект');
  expect(controls.querySelector<HTMLElement>('#music-direction-advanced-panel')?.hidden).toBe(true);
  expect(controls.querySelector('#studio-text')).toBeTruthy();
  expect(controls.querySelector<HTMLElement>('#music-prose-words')?.hidden).toBe(true);
  (controls.querySelector<HTMLButtonElement>('#music-direction-scratch')!).click();
  expect(controls.querySelector<HTMLElement>('#music-direction-advanced-panel')?.hidden).toBe(false);
  (controls.querySelector<HTMLButtonElement>('#music-direction-resume')!).click();
  expect(notice).toHaveBeenCalledWith('Сохранённой идеи пока нет.');
 });
 it('shows words handed over from Prose Studio and can clear them',async()=>{
  const w=realm();
  w.localStorage.setItem('pulse.prose.handoff.v1',JSON.stringify({version:1,title:'Как есть',text:'[Drop]\nЭкстази в темноте.',sections:[{name:'Drop',line:'Экстази в темноте.'}],savedAt:1}));
  const {studioModule}=await import('../ui/studio-modules/music');
  const controls=w.document.createElement('div');
  const result=w.document.createElement('div');
  w.document.body.append(controls,result);
  const context={meta:studioModule,controls,result,account:null,projectId:'',composer:w.document.createElement('form'),missionPanel:w.document.createElement('div'),api:vi.fn(async()=>({items:[]})),blobAPI:vi.fn(),notice:vi.fn(),failure:vi.fn(),mountDraft:vi.fn(),setMediaCleanup:vi.fn(),setLastBlob:vi.fn(),current:()=>true} as unknown as StudioModuleContext;
  await studioModule.mount(context);
  const words=controls.querySelector<HTMLElement>('#music-prose-words');
  expect(words?.hidden).toBe(false);
  expect(words?.textContent).toContain('Экстази в темноте.');
  expect(words?.textContent).toContain('не поёт');
  (words?.querySelector('button') as HTMLButtonElement).click();
  expect(words?.hidden).toBe(true);
  expect(w.localStorage.getItem('pulse.prose.handoff.v1')).toBeNull();
 });
 it('builds three original sketches without inventing a reference tempo',()=>{
  const plans=sketchRequests(prefs);
  expect(plans.map(plan=>plan.title)).toEqual(['Мягче','Темнее','Энергичнее']);
  for(const plan of plans){
   expect(plan.input.bpm).toBeNull();
   expect(plan.input.bars).toBe(16);
   expect(plan.input.prompt).toContain('не копия');
   expect(plan.input.prompt).not.toContain('128');
  }
  const known=sketchRequest({...prefs,bpm:126,keyRoot:'A',scale:'minor'},'dark',0);
  expect(known.input.bpm).toBe(126);
  expect(known.input.keyRoot).toBe('A');
  expect(known.input.pattern).toBe('bassline');
  const developed=developedRequest(known);
  expect(developed.input.arrangement).toBe('section-story');
  expect(developed.input.seed).toBe(known.input.seed);
  expect(developed.input.bars).toBe(315);
  expect(developed.input.story?.reduce((sum,block)=>sum+block.bars,0)).toBe(315);
  expect(developed.input.prompt).not.toContain('128');
  expect(developed.input.story?.map(block=>block.label)).toEqual(['Вступление','Развитие','Первый дроп','Брейк','Основной дроп','Завершение']);
  expect(partChangeText(['lead'])).toContain('Останется: мелодия');
  expect(partChangeText(['lead'])).toContain('Перепишу: бас');
 });
 it('reads the four edit phrases and rejects an unknown one',()=>{
  const sad=interpretMusicCommand('Бас оставь, мелодию сделай грустнее');
  expect(sad.keep).toEqual(['bass','pad','arp']);
  expect(sad.rewrite).toEqual(['lead']);
  expect(sad.mood).toBe('dark');
  expect(sad.summary).toContain('Останется: бас');
  expect(sad.summary).toContain('Перепишу: мелодия');
  const drop=interpretMusicCommand('Второй дроп мощнее, но без увеличения громкости');
  expect(drop.dropLevel).toBe(1.25);
  expect(drop.keep).toEqual(['bass','lead','pad','arp']);
  expect(drop.summary).toContain('Громкость микса не поднимается');
  const air=interpretMusicCommand('Добавь воздуха и сократи вступление');
  expect(air.synth).toBe('glass');
  expect(air.introBars).toBe(4);
  expect(air.rewrite).toEqual(['pad']);
  expect(air.keep).toEqual(['bass','lead','arp']);
  const tail=interpretMusicCommand('Переделай только последние 16 тактов');
  expect(tail.lastBars).toBe(16);
  expect(tail.summary).toContain('последние 16');
  expect(()=>interpretMusicCommand('')).toThrow(/Напиши/);
  expect(()=>interpretMusicCommand('сделай красиво')).toThrow(/Не понял/);
  const hook=interpretMusicCommand('Не трогай бас, перепиши хук');
  expect(hook.keep).toEqual(['bass','pad','arp']);
  expect(hook.rewrite).toEqual(['lead']);
  expect(interpretMusicCommand('Последние 8 тактов').lastBars).toBe(8);
  const lighter=interpretMusicCommand('Дроп легче');
  expect(lighter.dropLevel).toBe(.75);
  expect(lighter.summary).toContain('Громкость микса не поднимается');
  expect(interpretMusicCommand('Вступление длиннее').introBars).toBe(12);
  expect(interpretMusicCommand('Заглуши брейк').summary).toContain('Брейк заглушен.');
  expect(interpretMusicCommand('Заглуши вступление').summary).toContain('Вступление заглушено.');
  expect(interpretMusicCommand('Вступление ниже').sectionMove).toEqual({id:'intro',direction:1});
  expect(interpretMusicCommand('Поменяй вступление и развитие').sectionSwap).toEqual(['intro','rise']);
  expect(()=>interpretMusicCommand('Последние 7 тактов')).toThrow(/4, 8, 16 или 32/);
  const phrase=interpretMusicCommand('Фраза: ночной город один огонь');
  expect(phrase.phrase).toBe('ночной город один огонь');
  expect(phrase.summary).toContain('Музыка остаётся');
  expect(()=>interpretMusicCommand('Фраза: да')).toThrow(/4 до 8/);
  const longer=interpretMusicCommand('Первый дроп длиннее');
  expect(longer.lengthen).toBe('drop-1');
  expect(longer.introBars).toBeUndefined();
  expect(interpretMusicCommand('Дроп длиннее').lengthen).toBe('drop-2');
  expect(interpretMusicCommand('Вступление длиннее').introBars).toBe(12);
  setDirectionFlags({hookLift:true,professional:true,wish:'шире хук',roles:['bass']});
  const flagged=developedRequest(sketchRequest({...prefs,bpm:126,keyRoot:'A',scale:'minor'},'dark',0));
  expect(flagged.input.hookLift).toBe(true);
  expect(flagged.input.prompt).toContain('Мелодия новая');
  expect(flagged.input.prompt).toContain('пик не выше -1.0 dBTP');
  expect(flagged.input.prompt).not.toContain('128');
  setDirectionFlags({hookLift:false,professional:false,wish:'',roles:[]});
 });
});
