 it('holds the theme and leaves the break empty',()=>{
  const base={prompt:'hook',bpm:124,keyRoot:'A',scale:'minor' as const,bars:4,timeSignature:'4/4' as const,genre:'melodic-techno' as const,mood:'hypnotic' as const,pattern:'pulse' as const,arrangement:'section-story' as const,synthPreset:'warm-pad' as const,seed:7};
  const first=composeMusicSession({...base,story:[{id:'drop-1',label:'Первый дроп',bars:4,level:1}]});
  const second=composeMusicSession({...base,story:[{id:'drop-2',label:'Основной дроп',bars:4,level:1}]});
  const lead=(session:{notes:Array<{part:string;start:number;pitch:number;length:number}>})=>session.notes.filter(note=>note.part==='lead');
  const arp=(session:{notes:Array<{part:string;length:number}>})=>session.notes.filter(note=>note.part==='arp');
  expect(lead(second).length).toBeGreaterThan(lead(first).length);
  expect(lead(first).length).toBeGreaterThan(0);
  expect(lead(first).every(note=>note.start>=8&&note.length>=0.3)).toBe(true);
  expect(lead(second).every(note=>note.length>=0.3)).toBe(true);
  expect(arp(second).some(note=>note.length<0.3)).toBe(true);
  expect(lead(second).map(note=>note.pitch)).not.toEqual(lead(first).map(note=>note.pitch));
  const barsOf=(session:{notes:Array<{part:string;start:number}>},part:string)=>new Set(session.notes.filter(note=>note.part===part).map(note=>Math.floor(note.start/4)));
  for(const bar of barsOf(second,'lead'))expect(barsOf(second,'arp').has(bar)).toBe(false);
  for(const bar of barsOf(second,'lead'))expect(barsOf(second,'pad').has(bar)).toBe(false);
  expect(answerDegrees(7)).not.toEqual(hookDegrees(7));
  const grid=composeMusicSession({...base,bars:32,story:[{id:'intro',label:'Вступление',bars:8,level:.46},{id:'break',label:'Брейк',bars:8,level:.38},{id:'drop-2',label:'Основной дроп',bars:16,level:1}]});
  expect(grid.notes.some(note=>note.part==='pad'&&note.start<32)).toBe(true);
  const introPads=grid.notes.filter(note=>note.part==='pad'&&note.start<32);
  expect(new Set(introPads.map(note=>note.start)).size).toBe(introPads.length);
  expect(grid.notes.some(note=>note.part==='bass'&&note.start<32)).toBe(false);
  expect(grid.notes.some(note=>note.part==='lead'&&note.start<32)).toBe(false);
  expect(grid.notes.some(note=>note.part==='bass'&&note.start>=32&&note.start<64)).toBe(false);
  expect(grid.notes.some(note=>note.part==='lead'&&note.start>=32&&note.start<64)).toBe(false);
  expect(grid.notes.some(note=>note.part==='arp'&&note.start>=32&&note.start<64)).toBe(true);
  expect(grid.notes.some(note=>note.part==='lead'&&note.start>=64)).toBe(true);
  const fullStory=tenMinuteStory(124),full=composeMusicSession({...base,bars:310,story:fullStory});
  let cursor=0;const beats=new Map<string,[number,number]>();
  for(const block of fullStory){beats.set(block.id,[cursor*4,(cursor+block.bars)*4]);cursor+=block.bars;}
  const inside=(id:string,part:string,from=0,until=1)=>full.notes.some(note=>note.part===part&&note.start>=beats.get(id)![0]+from&&note.start<beats.get(id)![0]+(beats.get(id)![1]-beats.get(id)![0])*until);
  expect(inside('intro','pad')).toBe(true);
  expect(inside('intro','bass')).toBe(false);
  expect(inside('intro','lead')).toBe(false);
  expect(inside('rise','bass')).toBe(true);
  expect(inside('rise','lead')).toBe(false);
  expect(inside('break','bass')).toBe(false);
  expect(inside('break','lead')).toBe(false);
  expect(inside('break','arp')).toBe(true);
  expect(inside('drop-2','lead')).toBe(true);
  expect(inside('outro','lead')).toBe(true);
  expect(inside('outro','bass')).toBe(true);
  const grown=[{id:'drop-1',label:'Первый дроп',bars:6,level:1},{id:'break',label:'Брейк',bars:2,level:.4}];
  const short=[{id:'drop-1',label:'Первый дроп',bars:4,level:1},{id:'break',label:'Брейк',bars:4,level:.4}];
  const oldNotes=composeMusicSession({...base,bars:8,story:short}).notes;
  const fresh=composeMusicSession({...base,bars:8,story:grown}).notes;
  const filled=fillGrownSection(placeStoryNotes(oldNotes,short,grown,4),fresh,short,grown,4);
  expect(filled.some(note=>note.start>=16)).toBe(true);
  expect(vocalPhrases('Ночной город один огонь в окне')).toHaveLength(1);
  expect(vocalPhrases('Ночной город один огонь. Тихий двор держит тот же свет')).toHaveLength(2);
  const recorded=spokenFromRecording(Float32Array.from({length:44100},(_,index)=>Math.sin(index/20)*.2),44100,'ночной город один огонь');
  expect(recorded?.slices).toHaveLength(4);
  expect(recorded?.phrase).toContain('запись');
  expect(spokenFromRecording(new Float32Array(80),44100,'ночной город один огонь')).toBeNull();
 });
 it('keeps a pinned part and rewrites the others across a longer story',()=>{
  const input={prompt:'warehouse',bpm:124,keyRoot:'A',scale:'minor' as const,bars:64,timeSignature:'4/4' as const,genre:'melodic-techno' as const,mood:'dark' as const,pattern:'bassline' as const,arrangement:'section-story' as const,synthPreset:'sub' as const};
  const story=composeMusicSession(input);
  expect(story.bars).toBe(64);
  expect(story.notes.some(note=>note.start>=240)).toBe(true);
  expect(storySections(64).map(section=>section.label)).toEqual(['Вступление','Развитие','Первый дроп','Брейк','Основной дроп','Завершение']);
  expect(storySections(64)[0]?.to).toBe(8);
  expect(storySections(64,4)[0]?.to).toBe(4);
  expect(storySections(64,4).map(section=>section.label)).toEqual(['Вступление','Развитие','Первый дроп','Брейк','Основной дроп','Завершение']);
  const tail=rewriteTail([{part:'bass',pitch:36,start:0,length:4,velocity:.5},{part:'lead',pitch:60,start:14,length:4,velocity:.5}],[{part:'lead',pitch:72,start:10,length:1,velocity:.5},{part:'lead',pitch:74,start:16,length:2,velocity:.5}],16,32);
  expect(tail.map(note=>[note.part,note.start,note.length,note.pitch])).toEqual([['bass',0,4,36],['lead',14,2,60],['lead',16,2,74]]);
  expect(matchPlaybackGain(.2,.1)).toEqual({a:.5,b:1});
  expect(matchPlaybackGain(.05,.2)).toEqual({a:1,b:.25});
  expect(matchPlaybackGain(0,.2)).toEqual({a:1,b:1});
  expect(composeMusicSession({...input,bars:65}).bars).toBe(65);
  expect(()=>composeMusicSession({...input,bars:641})).toThrow();
  const full=tenMinuteStory(124,'4/4');
  expect(tenMinuteBars(124,'4/4')).toBe(310);
  expect(tenMinuteBars(120,'4/4')).toBe(300);
  expect(tenMinuteBars(126,'4/4')).toBe(315);
  expect(full.reduce((sum,block)=>sum+block.bars,0)).toBe(310);
  expect(full.map(block=>block.label)).toEqual(['Вступление','Развитие','Первый дроп','Брейк','Основной дроп','Завершение']);
  expect(masterGainDb(-14,-6)).toBe(5);
  expect(masterGainDb(-8,-0.2)).toBeCloseTo(-0.8);
  const line=vocalLine('[Текст]\nНочной город один огонь в окне');
  expect(line).toBe('Ночной город один огонь в окне');
  expect(vocalLine('да')).toBeNull();
  const spoken=line?spokenFrom(line):null;
  expect(spoken?.slices.length).toBe(6);
  expect(spoken?.samples.some(sample=>Math.abs(sample)>0.01)).toBe(true);
  const previous=[{part:'bass' as const,pitch:36,start:0,length:1,velocity:.5},{part:'lead' as const,pitch:60,start:0,length:1,velocity:.5}];
  const fresh=[{part:'bass' as const,pitch:40,start:0,length:1,velocity:.5},{part:'bass' as const,pitch:41,start:4,length:1,velocity:.5},{part:'lead' as const,pitch:72,start:0,length:1,velocity:.5},{part:'lead' as const,pitch:74,start:4,length:1,velocity:.5}];
  const kept=keepMusicParts(previous,fresh,['bass'],1,2,4);
  expect(kept.filter(note=>note.part==='bass').map(note=>[note.start,note.pitch])).toEqual([[0,36],[4,36]]);
  expect(kept.filter(note=>note.part==='lead').map(note=>note.pitch)).toEqual([72,74]);
  const blocks=storyBlocks();
  expect(blocks.map(block=>block.label)).toEqual(['Вступление','Развитие','Первый дроп','Брейк','Основной дроп','Завершение']);
  expect(blocks.reduce((sum,block)=>sum+block.bars,0)).toBe(64);
  const swapped=moveStoryBlock(blocks,0,1);
  expect(swapped.map(block=>block.id).slice(0,2)).toEqual(['rise','intro']);
  expect(moveStoryBlock(blocks,0,-1).map(block=>block.id)).toEqual(blocks.map(block=>block.id));
  const notes=[{part:'bass' as const,pitch:36,start:0,length:1,velocity:.5},{part:'lead' as const,pitch:72,start:32,length:1,velocity:.5}];
  expect(placeStoryNotes(notes,blocks,swapped,4).map(note=>[note.part,note.start,note.pitch])).toEqual([['lead',0,72],['bass',32,36]]);
  const muted=toggleStoryMute(blocks,0);
  expect(placeStoryNotes(notes,blocks,muted,4).map(note=>note.part)).toEqual(['lead']);
  expect(storyBlockLevel(muted,0)).toBe(0);
  expect(storyBlockLevel(muted,8)).toBe(.64);
  expect(swapStoryBlocks(blocks,'intro','rise').map(block=>block.id).slice(0,2)).toEqual(['rise','intro']);
  expect(()=>swapStoryBlocks(blocks,'intro','break')).toThrow(/соседние/);
 });
