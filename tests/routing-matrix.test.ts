const WITH_IMAGE_GAPS = ["добавь шляпу"]; // неоднозначно с правкой текста на приложенном скриншоте

const REPEAT = [
  "рисуй",
  "давай рисуй",
  "нарисуй это",
  "нарисуй",
  "рисуй её",
  "сделай картинку",
  "нарисуй пожалуйста",
];
const NOT_REPEAT = ["попробуй снова", "объясни DNS", "привет", "давай", "ок"];
const PREVIOUS = "красный дракон на скале";

describe("матрица маршрутизации чата", () => {
  it("таблица достаточно большая", () => {
    expect(ROUTES.length + FIRST_MATCH.length).toBeGreaterThanOrEqual(100);
  });

  it.each(ROUTES)("«%s» → %s", (phrase, kind) => {
    expect(readAssignment(phrase).kind).toBe(kind);
  });

  it.each(FIRST_MATCH)(
    "несколько действий в одной фразе, выигрывает первое совпадение: «%s» → %s",
    (phrase, kind) => {
      expect(readAssignment(phrase).kind).toBe(kind);
    },
  );

  it.each(ROUTE_GAPS)(
    "известный пробел: «%s» должно быть %s, сейчас %s",
    (phrase, _want, current) => {
      expect(readAssignment(phrase).kind).toBe(current);
    },
  );

  it.each(WITH_IMAGE_EDITS)("с картинкой: «%s» идёт в рисование", (phrase) => {
    expect(
      drawRequest(phrase, { hasImage: true, previous: "" }),
    ).not.toBeNull();
  });

  it.each(WITH_IMAGE_TALK)("с картинкой: «%s» не рисуется само", (phrase) => {
    expect(drawRequest(phrase, { hasImage: true, previous: "" })).toBeNull();
  });

  it.each(WITH_IMAGE_GAPS)(
    "известный пробел: с картинкой «%s» должно править картинку, сейчас нет",
    (phrase) => {
      expect(drawRequest(phrase, { hasImage: true, previous: "" })).toBeNull();
    },
  );

  it.each(REPEAT)("«%s» повторяет прошлый промпт", (phrase) => {
    expect(
      drawRequest(phrase, { hasImage: false, previous: PREVIOUS }),
    ).toEqual({ text: PREVIOUS });
  });

  it.each(NOT_REPEAT)(
    "«%s» не запускает рисование по прошлому промпту",
    (phrase) => {
      expect(
        drawRequest(phrase, { hasImage: false, previous: PREVIOUS }),
      ).toBeNull();
    },
  );

  it.each(["рисуй", "давай рисуй", "нарисуй это", "нарисуй"])(
    "без прошлого промпта «%s» не рисует вслепую",
    (phrase) => {
      expect(drawRequest(phrase, { hasImage: false, previous: "" })).toBeNull();
    },
  );
});

