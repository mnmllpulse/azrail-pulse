import { readFileSync } from 'node:fs';
const pkg=JSON.parse(readFileSync('package.json','utf8'));
const model=JSON.parse(readFileSync('config/environments.json','utf8'));
const configured=model.environments?.staging?.vars?.PUBLIC_ORIGINS?.split(',')?.[0]?.trim();
const base=(process.env.AZRAIL_URL||configured||'').replace(/\/$/,'');
if(!/^https:\/\//.test(base))throw Error('A canonical HTTPS staging URL is required for post-deploy health verification');
const endpoint=`${base}/health/live`;
const response=await fetch(endpoint,{method:'GET',headers:{accept:'application/json'},redirect:'error',signal:AbortSignal.timeout(20000)});
if(!response.ok)throw Error(`Staging /health/live returned HTTP ${response.status}`);
const body=await response.json();
if(body?.status!=='ok')throw Error(`Staging liveness status mismatch: expected ok, received ${body?.status??'missing'}`);
if(body?.version!==pkg.version)throw Error(`Staging version mismatch: expected ${pkg.version}, received ${body?.version??'missing'}`);
console.log(`STAGING AUTO-DEPLOY HEALTH VERIFIED: ${endpoint} reports status ok and version ${pkg.version}. Authenticated smoke remains a separate Stage D gate.`);
