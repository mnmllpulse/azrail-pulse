import { readFileSync, writeFileSync } from 'node:fs';

const pkg = JSON.parse(readFileSync('package.json', 'utf8'));
const version = String(pkg.version ?? '').trim();
if (!version) throw new Error('package.json version is required');

const replacements = [
  ['ui/app.html', /UNIFIED \/ [^<]+/, `UNIFIED / ${version}`],
  ['index.html', /UNIFIED \/ [^<]+/, `UNIFIED / ${version}`],
  ['site/app.html', /UNIFIED \/ [^<]+/, `UNIFIED / ${version}`],
  ['site/index.html', /UNIFIED \/ [^<]+/, `UNIFIED / ${version}`],
  ['public/ultimate.html', /ULTIMATE · [^<]+/, `ULTIMATE · ${version}`],
  ['src/unified/mcp-client.ts', /clientInfo:\{name:'azrail-pulse',version:'[^']+'\}/, `clientInfo:{name:'azrail-pulse',version:'${version}'}`],
];

for (const [file, pattern, replacement] of replacements) {
  const before = readFileSync(file, 'utf8');
  if (!pattern.test(before)) throw new Error(`Version marker not found in ${file}`);
  writeFileSync(file, before.replace(pattern, replacement));
}

const lock = JSON.parse(readFileSync('package-lock.json', 'utf8'));
lock.version = version;
if (lock.packages?.['']) lock.packages[''].version = version;
writeFileSync('package-lock.json', JSON.stringify(lock, null, 2) + '\n');

writeFileSync('src/build-info.ts', `// Generated by scripts/sync-version.mjs from package.json. Do not edit manually.\nexport const BUILD_VERSION = ${JSON.stringify(version)} as const;\n`);
console.log(`Version truth synchronized from package.json: ${version}`);
