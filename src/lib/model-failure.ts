/** Человеческая причина, когда ни одна модель не ответила. Текст ошибки провайдера наружу не отдаётся. */
export function unavailableReason(raw: string): string {
  const text = raw || "";
  if (
    /Дневная квота Workers AI|3036|daily free allocation|10,000 neurons/i.test(
      text,
    )
  ) {
    return "Модель недоступна: дневная квота Workers AI исчерпана, платный обход выключен. Обнулится завтра.";
  }
  if (/Суточный лимит нейронов/i.test(text)) {
    return "Модель недоступна: суточный лимит платных моделей исчерпан, а бесплатные сейчас не ответили. Повтори через несколько минут.";
  }
  if (/429|rate.?limit|quota|лимит|exhaust|too many/i.test(text)) {
    return "Модель недоступна: провайдер временно ограничил запросы. Повтори через несколько минут.";
  }
  if (/Ни одна модель не ответила|Попытки:/i.test(text)) {
    return "Модель недоступна: все модели из очереди сейчас не ответили. Повтори через минуту; если повторяется, это сбой провайдеров.";
  }
  return "Модель недоступна.";
}
